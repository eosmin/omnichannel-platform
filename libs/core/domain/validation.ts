import { z } from 'zod'

import { MessageLimits } from './conversation-constants'
import { SettingsLimits } from './settings-constants'
import { hasMisleadingCharacters, plainName } from './text'
import { canonicalTimezone } from './timezone'

// A uuid is valid in either case and the rows hold it in lower case: the server compares ids as strings, so it reads
// them in the one form (an id written in capitals is the same row, not a 404: QA OPS-RD-177). The schema of
// every `:id` of a path, and of the ids a body or a query carries, is this one.
export const lowercasedUuidSchema = z.uuid().transform(value => value.toLowerCase())
export const uuidSchema = lowercasedUuidSchema

// A whole number a query string carries (a page size, a version, a year): decimal digits and nothing else. `z.coerce.number()` reads
// ' ' as 0, '1e2' as 100, '0x10' as 16 and ' 5' as 5, so a value no screen sends passed as a number (QA HC-207). The bounds are the
// caller's and both ends are included. At most nine digits, so the number is exact and no bound needs a bigger one.
// Leading zeros are read as written ('0025' is 25): they are still digits, and no value changes by them
// The largest whole number `queryIntSchema` reads: nine digits
export const QUERY_INT_MAX = 999_999_999

export function queryIntSchema(
  min: number,
  max: number = QUERY_INT_MAX
): z.ZodType<number, string> {
  return z
    .string()
    .regex(/^\d{1,9}$/, { message: 'a whole number, in digits only' })
    .transform(Number)
    .pipe(z.number().int().min(min).max(max))
}

// Generated by the client, one per message it means to send: the browser queue uses a UUID. The same
// shape is checked where the key is read from the request and where it travels back to the browsers.
export const idempotencyKeySchema = z
  .string()
  .max(MessageLimits.IDEMPOTENCY_KEY_MAX_LENGTH)
  .regex(/^[A-Za-z0-9_-]+$/, { message: 'letters, digits, hyphens and underscores only' })

// Zod runs every check even when the format already failed, so a text that is no link is not this
// check's to refuse (and `new URL` would throw on it)
function hasNoCredentials(link: string): boolean {
  if (!URL.canParse(link)) return true
  const { username, password } = new URL(link)
  return username === '' && password === ''
}

// Names that stay on the machine or its network: they have no place in a link that comes from outside
const LOCAL_SUFFIXES: readonly string[] = [
  'localhost',
  'local',
  'localdomain',
  'internal',
  'intranet',
  'lan',
  'corp',
  'home',
  'arpa' // home.arpa, and the reverse zones
]
const IPV4_LITERAL = /^\d{1,3}(\.\d{1,3}){3}$/

// Control characters (tab, line breaks, NUL) and the invisible format ones (zero-width space, the
// bidi marks, overrides and isolates) make a link read differently from what it is. `new URL` strips
// a tab or a line break without a word, so the raw text is what is looked at, and its percent-decoded
// form too.
const HIDDEN_IN_LINK = /[\p{Cc}\p{Cf}]/u
// Once percent-decoded only the invisible format characters count (an encoded bidi override reorders
// the text the same as a raw one); an encoded line feed in a query (`?text=a%0Ab`) is inert
const HIDDEN_WHEN_DECODED = /\p{Cf}/u

function hasNoHiddenCharacters(link: string): boolean {
  if (HIDDEN_IN_LINK.test(link)) return false
  try {
    return !HIDDEN_WHEN_DECODED.test(decodeURIComponent(link))
  } catch {
    // A legacy escape (`%E9`) does not decode as UTF-8; it holds no hidden character either
    return true
  }
}

// An address (v4 or v6, in any spelling `new URL` normalizes), `localhost` and its subdomains, a name
// with no dot and the suffixes of a private network: all of them point inside the network of whoever
// follows the link. The providers hand out names, never addresses. A public name can still resolve to
// a private address, so the server that fetches one checks the answer of the DNS itself.
function hasPublicHostName(link: string): boolean {
  if (!URL.canParse(link)) return true
  const host = new URL(link).hostname.toLowerCase().replace(/\.$/, '')
  if (host === '' || host.startsWith('[') || IPV4_LITERAL.test(host) || !host.includes('.')) {
    return false
  }
  const suffix = host.slice(host.lastIndexOf('.') + 1)
  return !LOCAL_SUFFIXES.includes(suffix)
}

// A link that comes from outside (an ad's, a customer's) and may be drawn as a link or an image:
// only http and https, never `javascript:` or `data:`, no user or password in it, no hidden
// character, and a host that is a public-looking name. Being well formed says nothing about where it
// points: whatever fetches it from a server (Step 3.4) must still refuse private addresses itself.
export const httpUrl = (maxLength: number): z.ZodPipe<z.ZodString, z.ZodURL> =>
  z
    .string()
    .max(maxLength)
    // Before the url check: zod hands `.url` a link already stripped of its tabs and line breaks
    .refine(hasNoHiddenCharacters, { message: 'a link carries no hidden character' })
    .pipe(
      z
        .url({ protocol: /^https?$/ })
        .max(maxLength)
        .refine(hasNoCredentials, { message: 'a link carries no credentials' })
        .refine(hasPublicHostName, { message: 'a link points to a public host name' })
    )

// A name or a title: one visible line, in NFC so that "é" typed two ways is one name. No control
// character or line break, no line or paragraph separator, no invisible or direction-changing character
// (the joiners that emoji and Persian need stay), no pile of combining marks. Postgres text cannot hold a
// NUL character: it is a 400 here and not a 500 there.
export function singleLineText(
  maxLength: number,
  minLength = 0
): z.ZodPipe<z.ZodPipe<z.ZodString, z.ZodTransform<string, string>>, z.ZodString> {
  return z
    .string()
    .trim()
    .min(minLength)
    .max(maxLength)
    .transform(plainName)
    .pipe(
      z.string().refine(value => !hasMisleadingCharacters(value), {
        message: 'contains a control or invisible character'
      })
    )
}

// Text a person writes about someone, over several lines (a reason, a note): line breaks stay, in NFC and with \r\n read as \n. Every other
// control character (NUL, tab, escape), line or paragraph separator, invisible or direction-changing character and pile of combining marks
// is a 400: Postgres text cannot hold a NUL, and the rest would be drawn to whoever reads it.
export function multiLineText(
  maxLength: number,
  minLength = 0
): z.ZodPipe<z.ZodPipe<z.ZodString, z.ZodTransform<string, string>>, z.ZodString> {
  return z
    .string()
    .max(maxLength * 2)
    .transform(value => value.normalize('NFC').replaceAll('\r\n', '\n').trim())
    .pipe(
      z
        .string()
        .min(minLength)
        .max(maxLength)
        .refine(value => !hasMisleadingCharacters(value.replaceAll('\n', ' ')), {
          message: 'contains a control or invisible character'
        })
    )
}

// A zone of the IANA database, stored in its canonical spelling
export const timezoneSchema = z
  .string()
  .max(SettingsLimits.TIMEZONE_MAX_LENGTH)
  .transform((value, ctx) => {
    const zone = canonicalTimezone(value)
    if (zone === null) ctx.addIssue({ code: 'custom', message: 'not a timezone' })
    return zone ?? z.NEVER
  })
