import type { Type } from '@nestjs/common'

import { isImageHostOrigin } from '@platform/core/domain'
import type { ChannelPlugin } from '@platform/plugins/sdk'

// The hosts the browser may load the pictures of the channels from (Content-Security-Policy `img-src`), as the
// plugins declare them (`imageHosts`). The script `tools/generate-image-hosts.ts` writes them into a file
// the web app imports (Step 7.9 B2); the pure part lives here so that it can be tested.
export interface PluginImageHosts {
  readonly avatar: readonly string[]
  readonly media: readonly string[]
}

type Declares = Pick<ChannelPlugin, 'imageHosts'>

// Each host once, in the order the plugins are registered
// `wildcard` is the rule of the registry: only an official plugin may declare `https://*.host`, because a wildcard on
// a host that many tenants share would let any of them draw pictures into the inbox.
export function unionOfImageHosts(
  plugins: readonly Declares[],
  { wildcard = false }: { wildcard?: boolean } = {}
): PluginImageHosts {
  const collect = (which: 'avatar' | 'media'): string[] => {
    const seen = new Set<string>()
    for (const plugin of plugins) {
      for (const host of plugin.imageHosts?.[which] ?? []) {
        const declared: unknown = host
        if (!isImageHostOrigin(declared, { wildcard })) {
          throw new Error(`invalid ${which} image host: ${String(declared)}`)
        }
        seen.add(declared)
      }
    }
    return [...seen]
  }
  return { avatar: collect('avatar'), media: collect('media') }
}

export function renderImageHostsFile(hosts: PluginImageHosts): string {
  const list = (items: readonly string[]): string =>
    items.length === 0 ? '[]' : `[\n${items.map(item => `  '${item}'`).join(',\n')}\n]`
  return [
    '// Generated by tools/generate-image-hosts.ts from the `imageHosts` of the plugins. Do not edit:',
    '// run `pnpm gen:image-hosts`. No imports here: `next.config.ts` loads this before the aliases exist.',
    '',
    `export const PLUGIN_AVATAR_IMAGE_HOSTS: readonly string[] = ${list(hosts.avatar)}`,
    '',
    `export const PLUGIN_MEDIA_IMAGE_HOSTS: readonly string[] = ${list(hosts.media)}`,
    ''
  ].join('\n')
}

// The hosts the official plugins declare. They are plain fields set when the plugin is built, so the plugin is
// built with nothing in place of what it is made of; a plugin whose constructor starts using one of those makes
// this throw, and the generator says so instead of writing a wrong file.
export function officialImageHosts(plugins: readonly Type<ChannelPlugin>[]): PluginImageHosts {
  const built = plugins.map(plugin => new plugin({}, {}, {}))
  return unionOfImageHosts(built, { wildcard: true })
}
